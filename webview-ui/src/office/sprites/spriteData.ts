/**
 * Direction-agnostic sprite sets for the circus animation system.
 * Side-facing animations (walk, sit, attack) are right-facing; renderer flips for LEFT.
 * Front-facing animations (idle, celebrate) are never flipped.
 */
export interface CharacterSprites {
  idle: [SpriteData, SpriteData]
  walk: [SpriteData, SpriteData, SpriteData, SpriteData]
  sit: [SpriteData, SpriteData]
  attack: [SpriteData, SpriteData, SpriteData]
  celebrate: [SpriteData, SpriteData, SpriteData]
}

const spriteCache = new Map<string, CharacterSprites>()

/** Apply hue shift to every sprite in a CharacterSprites set */
function hueShiftSprites(sprites: CharacterSprites, hueShift: number): CharacterSprites {
  const color: FloorColor = { h: hueShift, s: 0, b: 0, c: 0 }
  const sh = (s: SpriteData) => adjustSprite(s, color)
  return {
    idle:      [sh(sprites.idle[0]),      sh(sprites.idle[1])],
    walk:      [sh(sprites.walk[0]),      sh(sprites.walk[1]),      sh(sprites.walk[2]),      sh(sprites.walk[3])],
    sit:       [sh(sprites.sit[0]),       sh(sprites.sit[1])],
    attack:    [sh(sprites.attack[0]),    sh(sprites.attack[1]),    sh(sprites.attack[2])],
    celebrate: [sh(sprites.celebrate[0]), sh(sprites.celebrate[1]), sh(sprites.celebrate[2])],
  }
}

export function getCharacterSprites(paletteIndex: number, hueShift = 0): CharacterSprites {
  const cacheKey = `${paletteIndex}:${hueShift}`
  const cached = spriteCache.get(cacheKey)
  if (cached) return cached

  let sprites: CharacterSprites

  if (loadedCharacters) {
    sprites = buildStandardSprites(loadedCharacters[paletteIndex % loadedCharacters.length])
  } else {
    // Fallback: hardcoded templates — map to new interface using right-facing frames
    const pal = CHARACTER_PALETTES[paletteIndex % CHARACTER_PALETTES.length]
    const r = (t: TemplateCell[][]) => resolveTemplate(t, pal)

    sprites = {
      idle:      [r(CHAR_WALK_DOWN_2),   r(CHAR_WALK_DOWN_2)],
      walk:      [r(CHAR_WALK_RIGHT_1),  r(CHAR_WALK_RIGHT_2), r(CHAR_WALK_RIGHT_3), r(CHAR_WALK_RIGHT_2)],
      sit:       [r(CHAR_RIGHT_TYPE_1),  r(CHAR_RIGHT_TYPE_2)],
      attack:    [r(CHAR_WALK_RIGHT_1),  r(CHAR_WALK_RIGHT_3), r(CHAR_WALK_RIGHT_2)],
      celebrate: [r(CHAR_DOWN_READ_1),   r(CHAR_DOWN_READ_2),  r(CHAR_WALK_DOWN_2)],
    }
  }

  if (hueShift !== 0) {
    sprites = hueShiftSprites(sprites, hueShift)
  }

  spriteCache.set(cacheKey, sprites)
  return sprites
}

/**
 * Build CharacterSprites from a standard 3-row 7-col sheet (112×96 palette chars).
 * Uses right-facing row for side animations; renderer flips for LEFT.
 * Front-facing (down) row used for idle/celebrate.
 */
function buildStandardSprites(char: LoadedCharacterData): CharacterSprites {
  const d = char.down
  const rt = char.right
  return {
    idle:      [d[1],  d[1]],
    walk:      [rt[0], rt[1], rt[2], rt[1]],
    sit:       [rt[3], rt[4]],
    attack:    [rt[0], rt[2], rt[1]],
    celebrate: [d[5],  d[6],  d[1]],
  }
}

/**
 * Build CharacterSprites from a circus 5-row 4-col sheet (192×240, 48×48 per frame).
 * The loader flattens all 5×4=20 frames row-major into `down`.
 *
 * Row-major frame indices (4 cols per row):
 *   Row 0 idle:      f[0]  f[1]  (f[2] f[3] empty)
 *   Row 1 walk:      f[4]  f[5]  f[6]  f[7]
 *   Row 2 sit:       f[8]  f[9]  (f[10] f[11] empty)
 *   Row 3 attack:    f[12] f[13] f[14] (f[15] empty)
 *   Row 4 celebrate: f[16] f[17] f[18] (f[19] empty)
 */
function buildCircusSprites(char: LoadedCharacterData): CharacterSprites {
  const f = char.down
  return {
    idle:      [f[0],  f[1]],
    walk:      [f[4],  f[5],  f[6],  f[7]],
    sit:       [f[8],  f[9]],
    attack:    [f[12], f[13], f[14]],
    celebrate: [f[16], f[17], f[18]],
  }
}

/**
 * Return sprites for a named character (case-insensitive), or null if not loaded.
 * Named sprites are used as-is without palette/hue modification.
 * Circus-format sheets have 20 frames flat in `down`; standard sheets have 7 per direction.
 */
export function getNamedCharacterSprites(name: string): CharacterSprites | null {
  const key = name.toLowerCase()
  const cacheKey = `name:${key}`
  const cached = spriteCache.get(cacheKey)
  if (cached) return cached
  const char = loadedNamedCharacters[key]
  if (!char) return null
  const sprites = char.down.length >= 20 ? buildCircusSprites(char) : buildStandardSprites(char)
  spriteCache.set(cacheKey, sprites)
  return sprites
}
